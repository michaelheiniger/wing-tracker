import org.jetbrains.compose.desktop.application.dsl.TargetFormat

plugins {
    id("wingtracker.compose")
}

kotlin {
    jvm {
        val main = compilations.getByName("main")
        // Sample-data tooling for development lives in its own compilation, so it is never part of the shipped app.
        val dev = compilations.create("dev") { associateWith(main) }
        compilations.getByName("test").associateWith(dev)

        tasks.register<JavaExec>("seedDevData") {
            group = "development"
            description = "Resets the development data folder and fills it with realistic sample data."
            classpath(dev.output.allOutputs, main.output.allOutputs, dev.runtimeDependencyFiles)
            mainClass.set("ch.qscqlmpa.wingtracker.desktop.dev.DevDataSeederKt")
        }
    }
    sourceSets {
        jvmTest.dependencies {
            implementation(libs.kotlinx.coroutines.test)
        }
        jvmMain.dependencies {
            implementation(project(":ui"))
            implementation(project(":application"))
            implementation(project(":infrastructure-storage-json"))
            implementation(project(":infrastructure-igc"))
            implementation(project(":infrastructure-syride"))
            implementation(libs.compose.material3)
            implementation(compose.desktop.currentOs)
            implementation(libs.kotlinx.coroutines.swing)
            implementation(libs.koin.core)
            implementation(libs.filekit.dialogs)
            implementation(libs.kotlinx.coroutines.core)
        }
    }
}

// Release version comes from the git tag via -PappVersion (ADR 0009).
val appVersion = providers.gradleProperty("appVersion").orElse("1.0.0")

compose.desktop {
    application {
        mainClass = "ch.qscqlmpa.wingtracker.desktop.MainKt"
        // Dev runs pass -Dwingtracker.dev=true; see the IntelliJ run configuration.
        jvmArgs += listOf("-Dwingtracker.dev=${providers.gradleProperty("wingtracker.dev").orElse("false").get()}")
        nativeDistributions {
            targetFormats(TargetFormat.Deb)
            packageName = "wing-tracker"
            // Generated by design/generate-icon.py.
            // FileKit's Linux dialogs (D-Bus) need this module in the packaged runtime.
            linux {
                iconFile.set(project.file("icons/icon.png"))
                modules("jdk.security.auth")
            }
            windows { iconFile.set(project.file("icons/icon.ico")) }
            macOS { iconFile.set(project.file("icons/icon.icns")) }
            packageVersion = appVersion.get()
        }
    }
}
