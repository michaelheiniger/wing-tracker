// The running app learns its version from a generated constant (ADR 0009), so dev runs and packages agree with Gradle.
val generateBuildInfo =
    tasks.register("generateBuildInfo") {
        val version = providers.gradleProperty("appVersion").orElse("dev")
        val outputDir = layout.buildDirectory.dir("generated/buildinfo")
        inputs.property("version", version)
        outputs.dir(outputDir)
        doLast {
            val file = outputDir.get().file("ch/qscqlmpa/wingtracker/desktop/BuildInfo.kt").asFile
            file.parentFile.mkdirs()
            file.writeText(
                """
                |package ch.qscqlmpa.wingtracker.desktop
                |
                |/** Generated by the generateBuildInfo task of app-desktop/build.gradle.kts. */
                |internal object BuildInfo {
                |    const val VERSION = "${version.get()}"
                |}
                |
                """.trimMargin(),
            )
        }
    }

kotlin {
