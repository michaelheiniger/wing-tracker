            implementation(project(":application"))
            implementation(project(":infrastructure-storage-json"))
            implementation(project(":infrastructure-igc"))
            implementation(project(":infrastructure-syride"))
            implementation(project(":infrastructure-spreadsheet"))
            implementation(project(":infrastructure-github-releases"))
            implementation(project(":infrastructure-map-tiles"))
            implementation(libs.compose.material3)
            implementation(compose.desktop.currentOs)
            implementation(libs.kotlinx.coroutines.swing)
            implementation(libs.koin.core)
            implementation(libs.filekit.dialogs)
            implementation(libs.kotlinx.coroutines.core)
            implementation(libs.kotlin.logging)
            // The logging backend is chosen here only; every other module sees just the facade (ADR 0023).
            implementation(libs.logback.classic)
        }
    }
}

// Release version comes from the git tag via -PappVersion (ADR 0009); the packaging tool needs a numeric one.
val appVersion = providers.gradleProperty("appVersion").orElse("1.0.0")

compose.desktop {
    application {
        mainClass = "ch.qscqlmpa.wingtracker.desktop.MainKt"
        // Dev runs pass -Dwingtracker.dev=true (DevMode); see the IntelliJ run configuration.
        jvmArgs += listOf("-Dwingtracker.dev=${providers.gradleProperty("wingtracker.dev").orElse("false").get()}")
        // Its banner would only clutter the console and the log.
        jvmArgs += listOf("-Dkotlin-logging.logStartupMessage=false")
        nativeDistributions {
            // Each is built only on its own OS (ADR 0009, ADR 0025).
            targetFormats(TargetFormat.Deb, TargetFormat.Msi)
            packageName = "wing-tracker"
            // The packaged runtime only holds the JDK modules listed here, and a missing one fails only when its code
            // first runs; verifyRuntimeModules (part of check) catches that. Every module the code refers to is
            // listed, even ones only an unused path needs, so the check needs no exceptions that could go stale.
            modules("java.instrument", "java.net.http", "jdk.net", "jdk.security.auth", "jdk.unsupported")
            // Generated by design/generate-icon.py.
            linux {
                iconFile.set(project.file("icons/icon.png"))
            }
            windows {
                iconFile.set(project.file("icons/icon.ico"))
                // Per user, so installing and updating need no administrator rights (ADR 0025).
                perUserInstall = true
                // Below the per-user programs folder, apart from the folders holding the log and the update files.
                installationPath = "Programs\\wing-tracker"
                // Never change it: it is how a newer installer recognises the installed version and replaces it.
                upgradeUuid = "9415c329-c70d-485e-8ab3-30d18fdeb4dc"
                menu = true
                shortcut = true
            }
            macOS { iconFile.set(project.file("icons/icon.icns")) }
            packageVersion = appVersion.get()
        }
    }
}

val verifyRuntimeModules =
    tasks.register<VerifyRuntimeModules>("verifyRuntimeModules") {
        group = "verification"
        description = "Checks that the packaged runtime holds every JDK module the application uses."
        // The same jars and JDK the packaging uses, so the check sees what the installed app will run. Read through a
        // plain provider, so the suggestion task's settings are used without running it.
        val suggest = provider { tasks.named<AbstractSuggestModulesTask>("suggestRuntimeModules").get() }
        classpath.from(suggest.map { it.files }, suggest.flatMap { it.launcherMainJar })
        javaHome.set(suggest.flatMap { it.javaHome })
        jvmTarget.set(suggest.flatMap { it.jvmTarget })
        runtimeRelease.set(
            tasks.named<AbstractJLinkTask>("createRuntimeImage").flatMap { it.destinationDir.file("release") },
        )
        report.set(layout.buildDirectory.file("reports/runtime-modules.txt"))
    }

tasks.named("check") { dependsOn(verifyRuntimeModules) }
